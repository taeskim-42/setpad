/// 표기: 값단위×횟수, x세트, 「메모」. 빈 자리는 '-', null 은 '거절'(세트가
/// 아니다 — 입력칸에 글이 남는다).
String show(ParsedSet? p) => p == null
    ? '거절'
    : [
        '${p.value == null ? '-' : '${formatNumber(p.value!)}${p.unit ?? ''}'}'
            '×${p.reps ?? '-'}',
        if (p.count > 1) 'x${p.count}',
        if (p.note != null) '「${p.note}」',
      ].join(' ');

