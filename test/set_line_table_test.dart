        ),
        (int n) => 'x$n',
      ]) {
        final again = parsePlanText(
          planText(plan.title, plan.items, f),
          previous: plan.items,
          title: plan.title,
        );
        expect(
          again.items.map((i) => (i.id, i.name, i.sets)),
          [(item.id, item.name, item.sets)],
          reason: '$line → ${planText(plan.title, plan.items, f)}',
        );
