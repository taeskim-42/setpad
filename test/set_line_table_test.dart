        reason: '$line (main: $main)',
      );
      expect(
        why.isNotEmpty,
        main != '${want.$1}(${want.$2})' || want.$3 != null,
        reason: '$line: 까닭 칸',
      );
      // 타이머는 이름에서 붙는다 — 친 줄에서 읽은 것과 같아야 한다.
