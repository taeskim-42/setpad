(int?, bool, int?, int?, int?)? timing(String name) =>
    switch (TimingSpec.parse(name)) {
      null => null,
      final t => (
        t.bpm,
        t.tabata,
        t.tabata ? t.work : null,
        t.tabata ? t.rest : null,
        t.tabata ? t.rounds : null,
      ),
    };

