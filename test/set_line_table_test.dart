  test('세트 줄 정답 표 — main 과 다른 줄은 까닭이 있다', () {
    expect(setLines.length, greaterThanOrEqualTo(150));
    expect(setLines.map((r) => r.$1).toSet().length, setLines.length);
    for (final (line, main, want, why) in setLines) {
      final got = parseSetLine(line);
      expect(show(got), want, reason: '$line (main: $main)');
      expect(why.isNotEmpty, main != want, reason: '$line: 까닭 칸');
      // 메모는 친 글의 조각이다 — 지어낸 말이 없다.
      for (final piece in got?.note?.split(' ') ?? const <String>[]) {
        expect(line.contains(piece), isTrue, reason: '$line: 메모 「$piece」');
      }
      // 거절한 줄 중 20세트 초과만 까닭이 따로 있다.
      expect(tooManySets(line), want == '거절' && why == cap, reason: line);
    }
  });

  test('bpm 옆의 세트·횟수 수는 템포가 아니다 — 타이머, 제목 고치기, 입력 줄이 같은 규칙', () {
    // (제목, 읽는 템포, 60 으로 고친 제목)
    const titles = [
      ('푸시업 bpm 3세트', 120, '푸시업 60bpm 3세트'),
      ('푸시업 bpm 3 sets', 120, '푸시업 60bpm 3 sets'),
      ('푸시업 bpm 100개', 120, '푸시업 60bpm 100개'),
      ('스쿼트 3x10 bpm 30', 30, '스쿼트 3x10 bpm 60'),
      ('스쿼트 3 x 10 bpm', 120, '스쿼트 3 x 10 60bpm'),
      ('스쿼트 20회 30 bpm 3세트', 30, '스쿼트 20회 60 bpm 3세트'),
      ('스쿼트 bpm 30 3세트', 30, '스쿼트 bpm 60 3세트'),
      ('버피 bpm:40', 40, '버피 bpm:60'),
      ('버피 40bpm', 40, '버피 60bpm'),
      ('버피 bpm40', 40, '버피 bpm60'),
      // 'x' 앞의 공백, 세는 말(셋·번·칸·라운드), 한 자리 수 — 템포가 아니다.
      ('스쿼트 bpm 3 x 10', 120, '스쿼트 60bpm 3 x 10'),
      ('푸시업 bpm 20 x 5', 120, '푸시업 60bpm 20 x 5'),
      ('푸시업 bpm 3셋', 120, '푸시업 60bpm 3셋'),
      ('푸시업 bpm 3번', 120, '푸시업 60bpm 3번'),
      ('푸시업 bpm 1칸 100개', 120, '푸시업 60bpm 1칸 100개'),
      ('버피 bpm 40 라운드', 120, '버피 60bpm 40 라운드'),
      ('푸시업 bpm 5', 120, '푸시업 60bpm 5'),
    ];
    for (final (title, bpm, fixed) in titles) {
      expect(TimingSpec.parse(title)?.bpm, bpm, reason: title);
      expect(const TimingSpec(bpm: 60).applyTo(title), fixed, reason: title);
    }
    // 입력 줄: 템포 말고 수가 남으면 설정을 묻는다(모델로 간다).
    for (final (line, asks) in [
      ('푸시업 bpm 3세트', true),
      ('스쿼트 3x10 bpm 30', true),
      ('버피 bpm 60', false),
      ('버피 60 bpm x8', false),
      ('스쿼트 bpm 3 x 10', true),
      ('푸시업 bpm 3셋', true),
      ('푸시업 bpm 1칸 100개', true),
    ]) {
      expect(
        hasSetupIntent(line.replaceAll(timerTokens, ' ')),
        asks,
        reason: line,
      );
    }
  });
}
