      if (plan.targets[item.id] case final t?) {
        expect(planTarget(t, 'kg')?.isEmpty, isFalse, reason: line);
      }
      // 다시 열어도 같은 계획이다 — 어느 언어의 세트 표기로 그려도.
      for (final f in [
